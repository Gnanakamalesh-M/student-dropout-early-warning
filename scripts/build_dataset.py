"""Build the modelling dataset from raw OULAD.

Raw CSVs -> validation -> clickstream aggregation -> labelled checkpoint
population -> ``data/interim/``.

Produces:

* ``data/interim/engagement_student_day.parquet`` — clickstream aggregated
  from 10.7M resource-day rows to 1.8M student-day rows.
* ``data/interim/checkpoints.parquet`` — the labelled (student, checkpoint)
  population defined by docs/TASK_SPEC.md.
* ``reports/population_report.md`` — auditable exclusion counts for the data
  card.

Usage::

    python scripts/build_dataset.py
    python scripts/build_dataset.py --force   # rebuild the clickstream too
"""

from __future__ import annotations

import argparse
import sys

from dropout_ews.config.settings import DATA_DIR, REPORTS_DIR, load_feature_config
from dropout_ews.data.checkpoints import build_checkpoint_rows
from dropout_ews.data.clickstream import build_student_day_engagement, engagement_summary

CHECKPOINTS_PARQUET = DATA_DIR / "interim" / "checkpoints.parquet"
POPULATION_REPORT = REPORTS_DIR / "population_report.md"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="rebuild the clickstream aggregation")
    args = parser.parse_args()

    config = load_feature_config()
    print(
        f"Task: P(withdraw within {config.task.horizon_days} days) "
        f"at checkpoints {config.task.checkpoints}"
    )

    print("\n[1/3] Aggregating clickstream (DuckDB, out of core)...")
    build_student_day_engagement(force=args.force)
    summary = engagement_summary()
    print(
        f"      {summary['rows']:,} student-day rows for "
        f"{summary['students']:,} students ({summary['file_mb']} MB parquet)"
    )

    print("\n[2/3] Building labelled checkpoint population...")
    population, report = build_checkpoint_rows()

    # The empty check lives here rather than in the invariants: an empty
    # population is legitimate for a degenerate cohort but always a bug for a
    # real build.
    if population.empty:
        print("ERROR: constructed population is empty", file=sys.stderr)
        return 1

    CHECKPOINTS_PARQUET.parent.mkdir(parents=True, exist_ok=True)
    population.to_parquet(CHECKPOINTS_PARQUET, index=False, compression="zstd")
    print(
        f"      {len(population):,} rows, {report.total_positives:,} positives "
        f"({100 * report.positive_rate:.2f}%)"
    )

    print("\n[3/3] Writing population report...")
    POPULATION_REPORT.parent.mkdir(parents=True, exist_ok=True)
    POPULATION_REPORT.write_text(
        "# Population report\n\n"
        "Generated by `scripts/build_dataset.py`. Defined by "
        "[docs/TASK_SPEC.md](../docs/TASK_SPEC.md).\n\n"
        f"Task: P(withdraw within {config.task.horizon_days} days) as of "
        f"course-relative day t, at checkpoints {config.task.checkpoints}.\n\n"
        + report.to_markdown()
        + "\n\n## Engagement coverage\n\n"
        + f"- Student-day rows: **{summary['rows']:,}**\n"
        + f"- Students with any VLE activity: **{summary['students']:,}**\n"
        + f"- Course-day range: **{summary['min_course_day']} to {summary['max_course_day']}**\n"
        + f"- Rows before day 0: **{summary['pre_start_rows']:,}**\n",
        encoding="utf-8",
    )
    print(f"      {POPULATION_REPORT}")

    print("\nDone.")
    print(report.to_markdown())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
